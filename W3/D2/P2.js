// Comparsion operators
console.log("Comparsion operators");
let x=3 ,y='3';
console.log("x==y: ",x==y); //loose equlity
console.log("x===y: ",x===y); //strict equlity
console.log("x!=y: ",x!=y); //loose inequlity
console.log("x!==y: ",x!==y); //strict inequlity
console.log("x>3: ",x>3);
console.log("x<3: ",x<3);
console.log("x>=3: ",x>=3);
console.log("x<=3: ",x<=3);